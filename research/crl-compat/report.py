"""Aggregates data/results.jsonl into results/results.json (every CRL x library) and results/RESULTS.md.

Usage: python3 -I report.py data/pairs.json data/results.jsonl
"""
import json, os, platform, statistics, sys
from collections import OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
LARGE = 1240  # asn1js's default of 10 000 nodes is reached at about this many entries (@peculiar/x509, PKI.js)

GROUPS = OrderedDict([
    ("rsa_small", f"RSA, up to {LARGE} entries"),
    ("rsa_large", f"RSA, more than {LARGE} entries"),
    ("ecdsa_p521", "ECDSA P-521 (AC Raiz v3)"),
    ("ecdsa_brainpool", "ECDSA brainpoolP512r1, explicit parameters (AC Raiz v4)"),
    ("ed448", "Ed448 (AC Raiz v6, AC INMETRO)"),
    ("ed521", "Ed521, OID 1.3.6.1.4.1.44588.2.1 (AC Raiz v7)"),
])
LIBS = ["OpenSSL CLI", "Go crypto/x509", "Python cryptography", "@peculiar/x509", "PKI.js", "node-forge", "@kya-brasil/core"]


def group(p):
    a = p["algorithm"]
    if "RSA" in a:
        return "rsa_large" if p["entries"] > LARGE else "rsa_small"
    if a == "ED448":
        return "ed448"
    if a.startswith("1.3.6.1.4.1.44588"):
        return "ed521"
    return "ecdsa_p521" if p["id"].endswith("v3") else "ecdsa_brainpool"


def main():
    meta = json.load(open(sys.argv[1]))
    pairs = {p["id"]: p for p in meta["pairs"]}
    rows = [json.loads(line) for line in open(sys.argv[2])]
    versions = {r["lib"]: r["version"] for r in rows}
    by = {(r["lib"], r["id"]): r for r in rows}
    verifiable = [p for p in meta["pairs"] if p["issuers"]]
    table = OrderedDict()
    for lib in LIBS:
        cells = OrderedDict()
        for g in GROUPS:
            ps = [p for p in verifiable if group(p) == g]
            ok = sum(1 for p in ps if by[(lib, p["id"])]["outcome"] == "ok")
            failures = sorted({by[(lib, p["id"])]["detail"] for p in ps if by[(lib, p["id"])]["outcome"] != "ok"})
            cells[g] = {"ok": ok, "n": len(ps), "failures": failures}
        ee = [p for p in verifiable if p["kind"] == "usuario-final"]
        big = by[(lib, "uf-ac-serpro-rfb-v5")]
        table[lib] = {"version": versions[lib], "groups": cells,
                      "end_entity_ok": sum(1 for p in ee if by[(lib, p["id"])]["outcome"] == "ok"), "end_entity_n": len(ee),
                      "total_ok": sum(c["ok"] for c in cells.values()), "total_n": len(verifiable),
                      "serpro_rfb_v5_ms": round(big["ms"], 1) if big["ms"] is not None else None}
    largest = pairs["uf-ac-serpro-rfb-v5"]
    out = {"fetched_at": meta["fetched_at"], "crls": len(meta["pairs"]), "verifiable": len(verifiable),
           "parse_only": [p["id"] for p in meta["pairs"] if not p["issuers"]], "unreachable": meta["missing"],
           "large_threshold": LARGE, "largest": {"id": largest["id"], "entries": largest["entries"], "bytes": largest["bytes"]},
           "group_labels": GROUPS, "libraries": table,
           "env": {"python": platform.python_version(), "machine": platform.machine(), "os": platform.platform()},
           "per_crl": [{"id": r["id"], "group": group(pairs[r["id"]]), "kind": pairs[r["id"]]["kind"], "entries": pairs[r["id"]]["entries"],
                        "lib": r["lib"], "outcome": r["outcome"], "detail": r["detail"], "ms": r["ms"]} for r in rows]}
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    json.dump(out, open(os.path.join(HERE, "results", "results.json"), "w"), indent=1)

    md = ["# Real ICP-Brasil CRLs across X.509 libraries", "",
          f"Generated by `pnpm --filter @kya-brasil/research-crl-compat all` from the CRLs fetched at {meta['fetched_at']}: "
          f"{len(meta['pairs'])} of {len(meta['pairs']) + len(meta['missing'])} sources reachable, {len(verifiable)} with the issuer's "
          "certificate (anchors/icp-brasil.pem, the AC Raiz roots, or the CRL's caIssuers). A cell counts the CRLs whose signature "
          "the library parsed and verified with that certificate.", "",
          "| Library | " + " | ".join(GROUPS.values()) + " | End-entity CRLs | All |",
          "|---|" + "---|" * (len(GROUPS) + 2)]
    for lib, t in table.items():
        md.append(f"| {lib} {t['version']} | " + " | ".join(f"{c['ok']}/{c['n']}" for c in t["groups"].values()) + f" | {t['end_entity_ok']}/{t['end_entity_n']} | {t['total_ok']}/{t['total_n']} |")
    md += ["", f"Largest CRL: {largest['id']}, {largest['entries']:,} entries, {largest['bytes']:,} bytes. Median of 3 parse+verify runs on it (OpenSSL CLI includes starting the process):", ""]
    md += [f"- {lib}: {t['serpro_rfb_v5_ms']} ms" if t["serpro_rfb_v5_ms"] is not None else f"- {lib}: refused" for lib, t in table.items()]
    md += ["", "## Why each library refuses", ""]
    for lib, t in table.items():
        reasons = sorted({f for c in t["groups"].values() for f in c["failures"]})
        if reasons:
            md.append(f"- **{lib}**: " + "; ".join(f"`{r[:120]}`" for r in reasons))
    fallback = [p for p in meta["pairs"] if p.get("via", "ac") != "ac"]
    if fallback:
        md += ["", "Taken from the kya-icp collector's latest copy because the AC's server did not answer this run: "
               + ", ".join(f"{p['id']} (`{p['via'].split(':', 1)[1]}`)" for p in fallback) + "."]
    md += ["", "Causes checked by hand:", "",
           "- `@peculiar/x509` 2.1.0 is what `@kya-brasil/core` up to 0.19.0 used. Its `X509Crl` parses through asn1js, whose default limit "
           "of 10 000 nodes refuses every CRL above about 1 240 entries; PKI.js parses with the same asn1js. Its `verify({ publicKey: X509Certificate })` "
           "takes the hash from the certificate's own signature algorithm, not the CRL's: AC SOLUTI RFB v1's CRL (sha256WithRSAEncryption) under a "
           "certificate signed with SHA-512 gives `false`, and `true` with a key imported for SHA-256. For Ed448 it also returns `false` instead of "
           "reporting the algorithm as unsupported, so a verifier cannot tell it from a forgery.",
           "- AC Raiz v4's key is brainpoolP512r1 written with explicit curve parameters; only OpenSSL maps them to the named curve. Web Crypto has no "
           "Brainpool curve, so the core refuses it as unsupported (REVOCATION_UNAVAILABLE).",
           "- 1.3.6.1.4.1.44588.2.1 is id-Ed521: PureEdDSA with SHAKE256 over the E-521 curve, adopted by ITI in DOC-ICP-01.01. It has no IETF "
           "specification, and none of the libraries here implements it.",
           "- Node 22 marks Ed448 in Web Crypto as experimental and prints a warning.", ""]
    md += ["Not verified: " + ", ".join(out["parse_only"]) + " (issuer certificate not found: retired AC, no caIssuers). Unreachable from the run: "
           + ", ".join(f"{m['id']} ({m['error'][:40]})" for m in meta["missing"]) + ".", ""]
    open(os.path.join(HERE, "results", "RESULTS.md"), "w").write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
