"""
Turn the Alloy instances of conformance.als into conformance vectors for @kya-brasil/core.

    java -jar org.alloytools.alloy.dist.jar exec -q -f -r 60 -t xml -o out docs/formal/conformance.als
    python3 -I docs/formal/generate-vectors.py out docs/vectors/mandate-conformance.json

Mapping from the model to the library's mandate format: Action atoms become action names ("act0"),
Currency atoms currency codes ("CUR0"), Party atoms counterparties ("party0.example"), the integer ceiling an
amount, and the integer validity bounds and the query's time days after 2027-01-01 (negative = before).
"""
import json
import os
import re
import sys
import xml.etree.ElementTree as ET
from datetime import datetime, timedelta, timezone

BASE = datetime(2027, 1, 1, tzinfo=timezone.utc)
EXPECT = {
    "SubsetYes": ("subset", True),
    "SubsetNo": ("subset", False),
    "AllowsYes": ("allows", True),
    "AllowsNo": ("allows", False),
    "Delegated": ("delegated", True),
    **{f"SubsetNo{r}": ("subset", False) for r in ("Acts", "Curs", "Ceiling", "Parties", "From", "Until")},
    **{f"AllowsNo{r}": ("allows", False) for r in ("From", "Until", "Action", "Cur", "Ceiling", "Party")},
}


def day(n):
    return (BASE + timedelta(days=int(n))).strftime("%Y-%m-%dT%H:%M:%SZ")


def name(atom):
    kind, idx = re.match(r".*?(Action|Currency|Party)\$(\d+)$", atom).groups()
    return {"Action": f"act{idx}", "Currency": f"CUR{idx}", "Party": f"party{idx}.example"}[kind]


def instance(path):
    inst = ET.parse(path).getroot().find("instance")
    fields = {}
    for f in inst.findall("field"):
        tuples = [[a.get("label") for a in t.findall("atom")] for t in f.findall("tuple")]
        fields.setdefault(f.get("label"), []).extend(tuples)

    def of(owner, field):
        return [t[1] for t in fields.get(field, []) if t[0] == owner]

    def mandate(owner):
        m = {}
        if of(owner, "ra"):
            m["actions"] = sorted(name(a) for a in of(owner, "acts"))
        if of(owner, "rc"):
            m["currencies"] = sorted(name(c) for c in of(owner, "curs"))
        parties = sorted(name(p) for p in of(owner, "parties"))
        if parties:
            m["counterparties"] = parties
        ceiling, cur = of(owner, "ceiling"), of(owner, "ceilCur")
        if ceiling:
            m["max_per_operation"] = {"amount": int(ceiling[0]), "currency": name(cur[0])}
        if of(owner, "validFrom"):
            m["valid_from"] = day(of(owner, "validFrom")[0])
        if of(owner, "validUntil"):
            m["valid_until"] = day(of(owner, "validUntil")[0])
        return m

    q = {"now": day(of("Q$0", "now")[0])}
    if of("Q$0", "act"):
        q["action"] = name(of("Q$0", "act")[0])
    if of("Q$0", "cur"):
        q["currency"] = name(of("Q$0", "cur")[0])
    if of("Q$0", "party"):
        q["counterparty"] = name(of("Q$0", "party")[0])
    if of("Q$0", "amount"):
        q["amount"] = int(of("Q$0", "amount")[0])
    return {"parent": mandate("P$0"), "child": mandate("C$0"), "query": q}


def main(src, dst):
    vectors = []
    for fname in sorted(os.listdir(src)):
        m = re.match(r"(\w+)-solution-(\d+)\.xml$", fname)
        if not m or m.group(1) not in EXPECT:
            continue
        kind, expected = EXPECT[m.group(1)]
        v = instance(os.path.join(src, fname))
        v.update({"command": m.group(1), "solution": int(m.group(2)), "check": kind, "expected": expected})
        vectors.append(v)
    vectors.sort(key=lambda v: (v["command"], v["solution"]))
    out = {
        "description": "Conformance vectors generated by Alloy from docs/formal/conformance.als (model: mandate.als). "
        "check=subset: isMandateSubset(parent, child) == expected; check=allows: checkAction(child, query).allowed == expected; "
        "check=delegated: the child is contained in the parent and allows the query, so checkAction(parent, query).allowed must be true.",
        "generator": "docs/formal/generate-vectors.py",
        "count": len(vectors),
        "vectors": vectors,
    }
    with open(dst, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    print(f"{len(vectors)} vectors -> {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
