"""
Turn the Alloy instances of timestamp.als (time-stamp on the principal's signature, SPEC section 23) into vectors
the library replays.

    java -jar org.alloytools.alloy.dist.jar exec -f -r 20 -t xml -o out-timestamp docs/formal/timestamp.als
    python3 -I docs/formal/generate-timestamp.py   # reads out-timestamp/, writes docs/vectors/timestamp-v1.json

Each vector is one signature and one certificate: when the signature was made, the time the credential declares, the
time a token attests (null = no token) and when the certificate was revoked (null = never). 1 model time unit = 1 day,
in seconds from 2027-01-01T00:00:00Z. `expected` is what revocationEffect must answer, under a policy that keeps an
authorization signed before the revocation, when it compares the revocation with the declared time and with the
attested one. The answer on the attested time is fixed by the command and checked here against the model's rule
(keptOn); the answer on the declared time is that same rule applied to the instance.
"""
import json
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "out-timestamp")
DST = os.path.join(ROOT, "docs", "vectors", "timestamp-v1.json")
DAY_S = 86400

# command: (answer on the attested time, note)
COMMANDS = {
    "StampNeverRevoked": ("none", None),
    "StampBeforeRevocation": ("none", None),
    "StampAtRevocation": ("revoke", None),
    "BackdatedAfterRevocation": ("revoke", "signed after the revocation and declared before it"),
    "NoStampDeclaredBefore": ("revoke", "no token: nothing to compare"),
    "ThiefInsideWindow": ("none", "assumption: the key was not stolen before the token's time"),
}


def fields(path):
    inst = ET.parse(path).getroot().find("instance")
    out = {}
    for f in inst.findall("field"):
        for t in f.findall("tuple"):
            atoms = [a.get("label") for a in t.findall("atom")]
            out[(f.get("label"), atoms[0])] = atoms[1]
    return lambda owner, field: out.get((field, owner))


def kept(t, revoked):
    """keptOn of timestamp.als."""
    return t is not None and (revoked is None or revoked > t)


def vector(of, command):
    num = lambda v: None if v is None else int(v)
    made, declared, stamp = num(of("S$0", "made")), num(of("S$0", "declared")), num(of("S$0", "stamp"))
    revoked = num(of("Cert$0", "revoked"))
    effect = lambda t: "none" if revoked is None or kept(t, revoked) else "revoke"
    attested, note = COMMANDS[command]
    if effect(stamp) != attested:
        raise SystemExit(f"{command}: the instance gives {effect(stamp)} on the attested time, the command says {attested}")
    sec = lambda t: None if t is None else t * DAY_S
    v = {"made": sec(made), "declared": sec(declared), "attested": sec(stamp), "revoked_at": sec(revoked),
         "by_thief": of("S$0", "byThief") is not None, "expected": {"on_declared": effect(declared), "on_attested": attested}}
    if note:
        v["note"] = note
    return v


def main():
    vectors = []
    for fname in sorted(os.listdir(SRC)):
        m = re.match(r"(\w+)-solution-(\d+)\.xml$", fname)
        if not m or m.group(1) not in COMMANDS:
            continue
        v = vector(fields(os.path.join(SRC, fname)), m.group(1))
        v.update({"command": m.group(1), "solution": int(m.group(2)), "source": "alloy"})
        vectors.append(v)
    vectors.sort(key=lambda v: (v["command"], v["solution"]))
    out = {
        "description": "Vectors generated by Alloy from the run commands of docs/formal/timestamp.als: one signature and one certificate "
        "(SPEC section 23). Times are seconds from the epoch, 1 model unit = 1 day; null = no token (attested) or never revoked (revoked_at). "
        "Under a policy whose effect for the revocation reason is 'keep', revocationEffect compared with the declared time must answer "
        "expected.on_declared and compared with the attested time (null when there is no token) expected.on_attested. made and by_thief are "
        "what the verifier cannot see. BackdatedAfterRevocation is the case the token exists for; ThiefInsideWindow is the one it does not "
        "solve, and the vector records that the library keeps it.",
        "generator": "docs/formal/generate-timestamp.py",
        "epoch": "2027-01-01T00:00:00Z",
        "count": len(vectors),
        "vectors": vectors,
    }
    with open(DST, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    print(f"{len(vectors)} vectors -> {DST}")


if __name__ == "__main__":
    main()
