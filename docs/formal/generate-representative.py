"""
Turn the Alloy instances of representative.als (company mandate signed by a legal representative, SPEC section 22)
into vectors the library replays.

    java -jar org.alloytools.alloy.dist.jar exec -f -r 20 -t xml -o out-representative docs/formal/representative.als
    python3 -I docs/formal/generate-representative.py   # reads out-representative/, writes docs/vectors/representative-v1.json

Each vector is one verification of a company mandate signed by a single certificate: which kind of certificate
signed (a natural person's e-CPF or the company's electronic seal), whether the verifier has a list of
representatives, whether the signer's CPF is in it, and whether the signed text is the mandate's text. `expected` is
ok or the reason of the refusal. StaleList and LentECpf are the trust assumptions the library cannot check: it
accepts them, and the vector records that it must.
"""
import json
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "out-representative")
DST = os.path.join(ROOT, "docs", "vectors", "representative-v1.json")

EXPECTED = {
    "RepListedSameText": {"ok": True},
    "RepNotListed": {"ok": False, "reason": "not-listed"},
    "RepOtherText": {"ok": False, "reason": "other-text"},
    "RepNoList": {"ok": False, "reason": "no-list"},
    "RepSeal": {"ok": False, "reason": "seal"},
    "RepStaleList": {"ok": True, "assumption": "list is accurate"},
    "RepLentECpf": {"ok": True, "assumption": "e-CPF operated by its owner"},
}


def fields(path):
    inst = ET.parse(path).getroot().find("instance")
    out = {}
    for f in inst.findall("field"):
        for t in f.findall("tuple"):
            atoms = [a.get("label") for a in t.findall("atom")]
            out.setdefault((f.get("label"), atoms[0]), []).append(atoms[1])
    return lambda owner, field: out.get((field, owner), [])


def vector(of, command):
    attempt = "Attempt$0"
    m = of(attempt, "m")[0]
    signer, firm = of(m, "signer")[0], of(m, "firm")[0]
    seal = signer.startswith("Seal$")
    v = {"signer": "seal" if seal else "e-cpf", "has_list": bool(of(attempt, "hasList")),
         "same_text": of(m, "signedText") == of(m, "challenge")}
    if not seal:
        owner = of(signer, "owner")[0]
        operator = of(signer, "operator")[0]
        v.update({"signer_listed": owner in set(of(firm, "listed")),
                  "signer_operated_by_owner": of(operator, "cpf")[0] == owner,
                  "signer_is_real_rep": operator in set(of(firm, "realReps"))})
    v["expected"] = EXPECTED[command]
    return v


def main():
    vectors = []
    for fname in sorted(os.listdir(SRC)):
        m = re.match(r"(\w+)-solution-(\d+)\.xml$", fname)
        if not m or m.group(1) not in EXPECTED:
            continue
        v = vector(fields(os.path.join(SRC, fname)), m.group(1))
        v.update({"command": m.group(1), "solution": int(m.group(2)), "source": "alloy"})
        vectors.append(v)
    vectors.sort(key=lambda v: (v["command"], v["solution"]))
    out = {
        "description": "Vectors generated by Alloy from the run commands of docs/formal/representative.als: one verification of a company "
        "mandate signed by a single certificate (SPEC section 22). signer=e-cpf: the mandate carries the representative line and is signed by "
        "a natural person's certificate; the verifier gives verifySelfIssuedCredential a representatives list iff has_list, and the list "
        "contains the signer's CPF iff signer_listed; same_text says whether the signed text is the mandate's text. signer=seal: the same "
        "text signed by the company's electronic seal (SE-S). expected is ok or the reason of the refusal (not-listed, other-text, no-list, "
        "seal). StaleList and LentECpf are accepted: the library cannot see who left the firm or who holds the token, and the vector records "
        "that assumption.",
        "generator": "docs/formal/generate-representative.py",
        "count": len(vectors),
        "vectors": vectors,
    }
    with open(DST, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    print(f"{len(vectors)} vectors -> {DST}")


if __name__ == "__main__":
    main()
