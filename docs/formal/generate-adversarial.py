"""
Turn the Alloy instances of adversarial.als (threat model, H4) into vectors the libraries replay.

    java -jar org.alloytools.alloy.dist.jar exec -q -f -r 20 -t xml -o out-adversarial docs/formal/adversarial.als
    python3 -I docs/formal/generate-adversarial.py   # reads out-adversarial/, writes docs/vectors/adversarial-v1.json

Replay vectors (1 model time unit = 100 s, so SKEW 3 = 300 s and MAXLIFE 6 = 600 s, the defaults of createKyaAuth):
one signed request with `created` and `expires`, presented at each time in `presented_at`, with the expected answer
for each presentation. Freshness vectors (1 unit = 1 h, MAXAGE 3 = 10 800 s): a CRL dated `this_update`, a
certificate revoked at `revoked_at` (or never), a verification at `now`, and whether checkFreshness must accept.
Times are seconds from 2027-01-01T00:00:00Z. Six hand-written vectors cover what the model's facts exclude.
"""
import json
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "out-adversarial")
DST = os.path.join(ROOT, "docs", "vectors", "adversarial-v1.json")
REPLAY_UNIT_S = 100
FRESH_UNIT_S = 3600
MAXAGE_UNITS = 3

REPLAY = {
    # command: (replay cache on?, expected per presentation in order of time)
    "ReplayInsideWindow": (True, ["ok", "KYA_REQUEST_REPLAYED"]),
    "ReplayAfterExpiry": (True, ["ok", "KYA_SIGNATURE_EXPIRED"]),
    "CreatedInFuture": (True, ["KYA_SIGNATURE_NOT_YET_VALID", "ok"]),
    "WindowEdges": (False, ["ok", "ok"]),
}
FRESH = {"FreshNotListed": True, "StaleNotListed": False, "FreshListed": False, "ResidualWindow": True, "AgeEdge": True}


def fields(path):
    inst = ET.parse(path).getroot().find("instance")
    out = {}
    for f in inst.findall("field"):
        for t in f.findall("tuple"):
            atoms = [a.get("label") for a in t.findall("atom")]
            out.setdefault((f.get("label"), atoms[0]), []).append(atoms[1])
    return lambda owner, field: out.get((field, owner), [])


def replay(of, command):
    cache, expected = REPLAY[command]
    created, expires = int(of("R$0", "created")[0]), int(of("R$0", "expires")[0])
    ats = sorted(int(of(a, "at")[0]) for a in ("A1$0", "A2$0"))
    return {"kind": "replay", "replay_cache": cache, "created": created * REPLAY_UNIT_S, "expires": expires * REPLAY_UNIT_S,
            "presented_at": [t * REPLAY_UNIT_S for t in ats], "expected": expected}


def fresh(of, command):
    this_update = int(of("threats/Crl$0", "thisUpdate")[0])
    now = int(of("T$0", "now")[0])
    rev = of("threats/Cred$0", "revokedAt")
    revoked_at = int(rev[0]) if rev else None
    return {"kind": "freshness", "this_update": this_update * FRESH_UNIT_S, "now": now * FRESH_UNIT_S,
            "revoked_at": None if revoked_at is None else revoked_at * FRESH_UNIT_S, "max_age_seconds": MAXAGE_UNITS * FRESH_UNIT_S,
            "expected_ok": FRESH[command]}


HAND = [
    # What the model's facts rule out, written by hand (source: "hand").
    {"command": "LifetimeTooLong", "kind": "replay", "replay_cache": False, "created": 0, "expires": 700, "presented_at": [100], "expected": ["KYA_SIGNATURE_TTL"]},
    {"command": "ExpiresBeforeCreated", "kind": "replay", "replay_cache": False, "created": 500, "expires": 400, "presented_at": [350], "expected": ["KYA_SIGNATURE_TTL"]},
    {"command": "ReplayAcrossClockSkew", "kind": "replay", "replay_cache": True, "created": 1000, "expires": 1600, "presented_at": [700, 1600], "expected": ["ok", "KYA_REQUEST_REPLAYED"]},
    {"command": "ReplayThenExpired", "kind": "replay", "replay_cache": True, "created": 0, "expires": 600, "presented_at": [100, 300, 601], "expected": ["ok", "KYA_REQUEST_REPLAYED", "KYA_SIGNATURE_EXPIRED"]},
    {"command": "StaleBySecond", "kind": "freshness", "this_update": 0, "now": 3 * FRESH_UNIT_S + 1, "revoked_at": None, "max_age_seconds": 3 * FRESH_UNIT_S, "expected_ok": False},
    {"command": "RevokedAtThisUpdate", "kind": "freshness", "this_update": 5 * FRESH_UNIT_S, "now": 6 * FRESH_UNIT_S, "revoked_at": 5 * FRESH_UNIT_S, "max_age_seconds": 3 * FRESH_UNIT_S, "expected_ok": False},
]


def main():
    vectors = []
    for fname in sorted(os.listdir(SRC)):
        m = re.match(r"(\w+)-solution-(\d+)\.xml$", fname)
        if not m or (m.group(1) not in REPLAY and m.group(1) not in FRESH):
            continue
        of = fields(os.path.join(SRC, fname))
        v = replay(of, m.group(1)) if m.group(1) in REPLAY else fresh(of, m.group(1))
        v.update({"command": m.group(1), "solution": int(m.group(2)), "source": "alloy"})
        vectors.append(v)
    vectors.sort(key=lambda v: (v["command"], v["solution"]))
    vectors += [{**h, "solution": 0, "source": "hand"} for h in HAND]
    out = {
        "description": "Adversarial vectors (H4) generated by Alloy from docs/formal/adversarial.als over the threat model threats.als, "
        "plus hand-written cases outside the model's facts. kind=replay: one request signed with created/expires (seconds from "
        "2027-01-01T00:00:00Z) and presented at each presented_at, with the expected result per presentation ('ok' or the error "
        "code of createKyaAuth, defaults maxSkewSeconds=300, maxTtlSeconds=600, replayCache=memoryReplayCache when replay_cache). "
        "kind=freshness: CRL evidence dated this_update, certificate revoked at revoked_at (null = never), checkFreshness at now "
        "with max_age_seconds as the ceiling must give ok == expected_ok.",
        "generator": "docs/formal/generate-adversarial.py",
        "epoch": "2027-01-01T00:00:00Z",
        "count": len(vectors),
        "vectors": vectors,
    }
    with open(DST, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    print(f"{len(vectors)} vectors -> {DST}")


if __name__ == "__main__":
    main()
